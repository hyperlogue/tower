use crate::{
    Paths, ensure_user_dir, environment, executable, read_config, remove_private, uid,
    write_owned_config,
};
use std::{
    io,
    path::PathBuf,
    process::{Command, Stdio},
};

pub struct ServiceFile {
    pub path: PathBuf,
    pub contents: String,
}
pub struct InstalledServices {
    pub files: Vec<PathBuf>,
    pub enabled: bool,
}
fn unit_value(value: &str) -> io::Result<String> {
    if value.chars().any(char::is_control) {
        return Err(io::Error::other(
            "service paths must not contain control characters",
        ));
    }
    Ok(format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    ))
}
fn xml(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}
pub fn service_files(
    paths: &Paths,
    program: &std::path::Path,
    mac: bool,
) -> io::Result<Vec<ServiceFile>> {
    let env = environment();
    let vars = [
        ("HOME", paths.home.to_string_lossy().into_owned()),
        (
            "PATH",
            env.get("PATH")
                .cloned()
                .unwrap_or_else(|| "/usr/bin:/bin".into()),
        ),
        (
            "XDG_STATE_HOME",
            paths
                .state
                .parent()
                .ok_or_else(|| io::Error::other("invalid state path"))?
                .to_string_lossy()
                .into_owned(),
        ),
        (
            "XDG_CONFIG_HOME",
            paths.config_home.to_string_lossy().into_owned(),
        ),
        ("TOWER_SOCKET", paths.socket.to_string_lossy().into_owned()),
    ];
    let mut files = Vec::new();
    for (name, args) in [
        ("tower-pool", ["__pool", "run"]),
        ("towerd", ["daemon", "run"]),
    ] {
        let (path, contents) = if mac {
            let label = format!("io.tower.{name}");
            let path = paths
                .home
                .join("Library/LaunchAgents")
                .join(format!("{label}.plist"));
            let env = vars
                .iter()
                .map(|(k, v)| format!("<key>{k}</key><string>{}</string>", xml(v)))
                .collect::<String>();
            let args = std::iter::once(program.to_string_lossy().into_owned())
                .chain(args.map(str::to_owned))
                .map(|a| format!("<string>{}</string>", xml(&a)))
                .collect::<String>();
            let log = xml(&paths.logs.join(format!("{name}.log")).to_string_lossy());
            (
                path,
                format!(
                    "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- Generated by tower -->\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<plist version=\"1.0\"><dict><key>Label</key><string>{label}</string><key>ProgramArguments</key><array>{args}</array><key>EnvironmentVariables</key><dict>{env}</dict><key>RunAtLoad</key><true/><key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict><key>Umask</key><integer>63</integer><key>StandardOutPath</key><string>{log}</string><key>StandardErrorPath</key><string>{log}</string></dict></plist>\n"
                ),
            )
        } else {
            let path = paths
                .config_home
                .join("systemd/user")
                .join(format!("{name}.service"));
            let env = vars
                .iter()
                .map(|(k, v)| unit_value(&format!("{k}={v}")).map(|q| format!("Environment={q}\n")))
                .collect::<io::Result<String>>()?;
            let dependencies = if name == "towerd" {
                "Wants=tower-pool.service\nAfter=tower-pool.service\n"
            } else {
                ""
            };
            let program = unit_value(&program.to_string_lossy())?.replace('$', "$$");
            (
                path,
                format!(
                    "# Generated by tower\n[Unit]\nDescription=Tower {name}\n{dependencies}\n[Service]\nType=simple\nExecStart={program} {} {}\n{env}UMask=0077\nRestart=on-failure\nRestartSec=2\nTimeoutStopSec=15\nKillMode=control-group\n\n[Install]\nWantedBy=default.target\n",
                    args[0], args[1]
                ),
            )
        };
        files.push(ServiceFile { path, contents });
    }
    Ok(files)
}
fn control(program: &str, args: &[&str]) -> bool {
    Command::new(program)
        .args(args)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .is_ok_and(|s| s.success())
}
pub fn install_services(paths: &Paths, write_only: bool) -> io::Result<InstalledServices> {
    paths.prepare()?;
    let mac = cfg!(target_os = "macos");
    let files = service_files(paths, &executable()?, mac)?;
    for file in &files {
        if let Some(text) = read_config(&file.path)?
            && !text.contains("Generated by tower")
        {
            return Err(io::Error::other(
                "service file already exists and is not owned by Tower",
            ));
        }
    }
    for file in &files {
        ensure_user_dir(
            file.path
                .parent()
                .ok_or_else(|| io::Error::other("invalid service path"))?,
        )?;
        write_owned_config(&file.path, file.contents.as_bytes())?;
    }
    let enabled = if write_only {
        false
    } else if mac {
        files.iter().all(|f| {
            control(
                "launchctl",
                &[
                    "bootstrap",
                    &format!("gui/{}", uid()),
                    &f.path.to_string_lossy(),
                ],
            )
        })
    } else {
        control("systemctl", &["--user", "daemon-reload"])
            && control(
                "systemctl",
                &["--user", "enable", "tower-pool.service", "towerd.service"],
            )
    };
    Ok(InstalledServices {
        files: files.into_iter().map(|f| f.path).collect(),
        enabled,
    })
}
pub fn uninstall_services(paths: &Paths, write_only: bool) -> io::Result<Vec<PathBuf>> {
    let mac = cfg!(target_os = "macos");
    let files = service_files(paths, &executable()?, mac)?;
    for file in &files {
        if let Some(text) = read_config(&file.path)?
            && !text.contains("Generated by tower")
        {
            return Err(io::Error::other(
                "refusing to remove a service not owned by Tower",
            ));
        }
    }
    if !write_only {
        if mac {
            // Removing registration can stop a launchd job. Leave live jobs alone;
            // deleting the plist disables next-login startup.
        } else if !control(
            "systemctl",
            &["--user", "disable", "tower-pool.service", "towerd.service"],
        ) {
            return Err(io::Error::other("cannot disable Tower services"));
        }
    }
    for file in &files {
        remove_private(&file.path)?;
    }
    if !mac && !write_only {
        control("systemctl", &["--user", "daemon-reload"]);
    }
    Ok(files.into_iter().map(|f| f.path).collect())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn service_jobs_have_separate_lifetimes_and_only_selected_environment() {
        let root = tempfile::tempdir().unwrap();
        let home = root.path();
        let paths = Paths {
            home: home.into(),
            state: home.join("s/tower"),
            config_home: home.join("c"),
            run: home.join("s/tower/run"),
            socket: home.join("s/tower/run/towerd.sock"),
            database: home.join("s/tower/tower.db"),
            tokens: home.join("s/tower/tokens"),
            logs: home.join("s/tower/logs"),
        };
        for mac in [false, true] {
            let files = service_files(
                &paths,
                std::path::Path::new("/opt/tower & tools/tower"),
                mac,
            )
            .unwrap();
            assert_eq!(files.len(), 2);
            assert!(
                !files
                    .iter()
                    .any(|f| f.contents.contains("TOWER_AGENT_TOKEN"))
            );
            if mac {
                assert!(files[0].contents.contains("&amp;"));
            } else {
                assert!(files[1].contents.contains("After=tower-pool.service"));
                assert!(!files[0].contents.contains("PartOf="));
            }
        }
    }
}
